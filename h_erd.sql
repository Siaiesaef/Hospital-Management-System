/* Patient Table */
CREATE TABLE IF NOT EXISTS Patient
(
patientID INTEGER PRIMARY KEY AUTO_INCREMENT,
pFirstName TEXT NOT NULL,
pMiddleName TEXT,
pLastName TEXT NOT NULL,
pDOB DATE NOT NULL,
pGender TEXT NOT NULL,
pAddress TEXT NOT NULL,
pCity TEXT NOT NULL,
pPostcode TEXT NOT NULL,
pEmail TEXT NOT NULL UNIQUE,
pPhoneNo TEXT NOT NULL UNIQUE,
pMemorableInfo TEXT NOT NULL
);

-- DROP TABLE Patient;

/* Staff Type Table */
CREATE TABLE IF NOT EXISTS StaffType 
(
staffTypeID INTEGER PRIMARY KEY AUTO_INCREMENT,
stSpeciality TEXT NOT NULL UNIQUE
);


/* Login Table */
CREATE TABLE IF NOT EXISTS Login
(
loginID INTEGER PRIMARY KEY AUTO_INCREMENT,
patientID INTEGER,
staffID INTEGER,
lUsername TEXT NOT NULL,
lHashPassword TEXT NOT NULL,
FOREIGN KEY (patientID) REFERENCES Patient(patientID)
ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (staffID) REFERENCES Staff(staffID)
ON DELETE CASCADE ON UPDATE CASCADE
);

/* Staff Table */
CREATE TABLE IF NOT EXISTS Staff
(
staffID INTEGER PRIMARY KEY AUTO_INCREMENT,
staffTypeID INTEGER,
sFirstName TEXT NOT NULL,
sMiddleName TEXT,
sLastName TEXT NOT NULL,
sEmail TEXT NOT NULL UNIQUE,
sType TEXT NOT NULL,
sPhoneNo TEXT NOT NULL UNIQUE,
sMemorableInfo TEXT NOT NULL,
FOREIGN KEY (staffTypeID) REFERENCES StaffType(staffTypeID) 
ON DELETE CASCADE ON UPDATE CASCADE
);

/* Prescription Table */
CREATE TABLE IF NOT EXISTS Prescription
(
prescriptionID INTEGER PRIMARY KEY AUTO_INCREMENT,
patientID INTEGER NOT NULL,
staffID INTEGER NOT NULL,
datePrescribed DATE NOT NULL,
dateCollected DATE,
medication TEXT NOT NULL,
dosage TEXT NOT NULL,
nextPickUp DATE,
repeatPrescription TEXT,
FOREIGN KEY (patientID) REFERENCES Patient(patientID)
ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (staffID) REFERENCES Staff(staffID)
ON DELETE CASCADE ON UPDATE CASCADE
);

/* Test Results Table */
CREATE TABLE IF NOT EXISTS TestResults
(
testResultsID INTEGER PRIMARY KEY AUTO_INCREMENT,
patientID INTEGER NOT NULL,
staffID INTEGER NOT NULL,
testResults TEXT NOT NULL,
dateTested DATE NOT NULL,
FOREIGN KEY (patientID) REFERENCES Patient(patientID)
ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (staffID) REFERENCES Staff(staffID)
ON DELETE CASCADE ON UPDATE CASCADE
);

/* Appointment Table */
CREATE TABLE IF NOT EXISTS Appointment
(
appointmentID INTEGER PRIMARY KEY AUTO_INCREMENT,
patientID INTEGER NOT NULL,
staffID INTEGER NOT NULL,
testResultsID INTEGER,
aDate DATE NOT NULL,
aTime TIME NOT NULL,
FOREIGN KEY (patientID) REFERENCES Patient(patientID)
ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (staffID) REFERENCES Staff(staffID)
ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (testResultsID) REFERENCES TestResults(testResultsID)
ON DELETE CASCADE ON UPDATE CASCADE
);
